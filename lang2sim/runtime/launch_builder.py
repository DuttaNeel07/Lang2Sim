def render(cfg: LaunchConfig) -> str:
    """Python source of the launch file for this config."""
    if not cfg.world_name:
        raise ValueError("world_name is required (the robot is spawned into it by name)")
    literal = pprint.pformat(asdict(cfg), indent=4, sort_dicts=True, width=100)
    return _TEMPLATE.replace("__CONFIG__", literal)


def write(cfg: LaunchConfig, out_dir: Path | None = None) -> Path:
    path = Path(out_dir or cfg.run_dir) / LAUNCH_FILE
    path.write_text(render(cfg), encoding="utf-8")
    return path
