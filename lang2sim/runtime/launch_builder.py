"""
Launch generator: one self-contained sim_launch.py per run.
File: lang2sim/runtime/launch_builder.py

Placed in runtime/ rather than compiler/ because the container imports it and
compiler/__init__.py pulls in jinja2/shapely, which the sim image does not ship.

The generated file is plain ROS 2 Python launch code with this run's settings
baked in as a dict literal at the top, so it can be read, diffed and re-run by
hand:  ros2 launch <run_dir>/sim_launch.py

It starts: Gazebo server (+ optional GUI that may be closed without stopping the
sim), robot_state_publisher, the TurtleBot3 Waffle spawned at the manifest's
pose, ros_gz_bridge (+ optional camera bridge), Nav2 with this run's map and AMCL
seeded at the spawn pose, and optional RViz2.

With telemetry on, the robot is spawned from the run's robot.l2s.sdf (chassis
bumper + ground-truth pose, see robot_instrument.py) and the bridge loads
bridge.l2s.yaml (stock topics + /lang2sim/contact_states and
/lang2sim/ground_truth/odom).
"""

from __future__ import annotations

import pprint
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import List

LAUNCH_FILE = "sim_launch.py"


@dataclass(frozen=True)
class LaunchConfig:
    run_dir: str                       # container path; logs and generated params go here
    world_sdf: str                     # container path, already checked/normalized
    world_name: str
    map_yaml: str
    x: float = 0.0
    y: float = 0.0
    yaw: float = 0.0
    gui: bool = True
    rviz: bool = True
    camera: bool = True                # image bridge; heavy under software rendering
    nav2_params: str = ""              # "" -> TurtleBot3 Waffle params
    nav2_delay_s: float = 5.0
    resource_paths: List[str] = field(default_factory=list)  # extra GZ_SIM_RESOURCE_PATH entries
    robot: str = "waffle"
    robot_sdf: str = ""                # "" -> stock TurtleBot3 model.sdf; else robot.l2s.sdf (bumper + ground truth)
    bridge_config: str = ""            # "" -> stock TurtleBot3 bridge yaml; else bridge.l2s.yaml (+ telemetry topics)


_TEMPLATE = '''\
"""Generated by lang2sim (lang2sim/runtime/launch_builder.py). Do not edit; regenerate instead."""
import math
import os

import yaml
from ament_index_python.packages import get_package_share_directory
from launch import LaunchDescription
from launch.actions import AppendEnvironmentVariable, IncludeLaunchDescription, TimerAction
from launch.launch_description_sources import PythonLaunchDescriptionSource
from launch_ros.actions import Node

CONFIG = __CONFIG__


def _nav2_params(tb3_nav):
    """Base Nav2 params with AMCL seeded at the spawn pose, written into the run folder."""
    base = CONFIG["nav2_params"] or os.path.join(tb3_nav, "param", CONFIG["robot"] + ".yaml")
    with open(base) as f:
        params = yaml.safe_load(f)
    amcl = params.setdefault("amcl", {}).setdefault("ros__parameters", {})
    amcl["set_initial_pose"] = True
    amcl["initial_pose"] = {"x": float(CONFIG["x"]), "y": float(CONFIG["y"]), "z": 0.0,
                            "yaw": float(CONFIG["yaw"])}
    for cm_key in ("global_costmap", "local_costmap"):
        cm_dict = params.get(cm_key, {}).get(cm_key, {}).get("ros__parameters", {})
        infl = cm_dict.get("inflation_layer", {})
        if infl:
            infl["inflation_radius"] = 0.35
            infl["cost_scaling_factor"] = 5.0
    out = os.path.join(CONFIG["run_dir"], "nav2_params.l2s.yaml")
    with open(out, "w") as f:
        yaml.safe_dump(params, f, sort_keys=False)
    return out


def generate_launch_description():
    tb3_gz = get_package_share_directory("turtlebot3_gazebo")
    tb3_nav = get_package_share_directory("turtlebot3_navigation2")
    ros_gz_sim = get_package_share_directory("ros_gz_sim")
    nav2_bringup = get_package_share_directory("nav2_bringup")
    model = "turtlebot3_" + CONFIG["robot"]

    with open(os.path.join(tb3_gz, "urdf", model + ".urdf")) as f:
        robot_description = f.read()

    actions = [AppendEnvironmentVariable("GZ_SIM_RESOURCE_PATH", p)
               for p in [os.path.join(tb3_gz, "models"), *CONFIG["resource_paths"]]]

    actions.append(IncludeLaunchDescription(
        PythonLaunchDescriptionSource(os.path.join(ros_gz_sim, "launch", "gz_sim.launch.py")),
        launch_arguments={"gz_args": "-r -s -v2 " + CONFIG["world_sdf"], "on_exit_shutdown": "true"}.items()))
    if CONFIG["gui"]:
        actions.append(IncludeLaunchDescription(
            PythonLaunchDescriptionSource(os.path.join(ros_gz_sim, "launch", "gz_sim.launch.py")),
            launch_arguments={"gz_args": "-g -v2", "on_exit_shutdown": "false"}.items()))

    actions.append(Node(
        package="robot_state_publisher", executable="robot_state_publisher", name="robot_state_publisher",
        output="screen", parameters=[{"use_sim_time": True, "robot_description": robot_description}]))
    actions.append(Node(
        package="ros_gz_sim", executable="create", output="screen",
        arguments=["-world", CONFIG["world_name"], "-name", CONFIG["robot"],
                   "-file", CONFIG["robot_sdf"] or os.path.join(tb3_gz, "models", model, "model.sdf"),
                   "-x", str(CONFIG["x"]), "-y", str(CONFIG["y"]), "-z", "0.01", "-Y", str(CONFIG["yaw"])]))
    actions.append(Node(
        package="ros_gz_bridge", executable="parameter_bridge", name="ros_gz_bridge", output="screen",
        parameters=[{"config_file": CONFIG["bridge_config"] or os.path.join(tb3_gz, "params", model + "_bridge.yaml"),
                     "use_sim_time": True}]))
    if CONFIG["camera"]:
        actions.append(Node(package="ros_gz_image", executable="image_bridge", name="ros_gz_image_bridge",
                            arguments=["/camera/image_raw"], output="screen"))

    actions.append(TimerAction(period=float(CONFIG["nav2_delay_s"]), actions=[IncludeLaunchDescription(
        PythonLaunchDescriptionSource(os.path.join(nav2_bringup, "launch", "bringup_launch.py")),
        launch_arguments={"map": CONFIG["map_yaml"], "use_sim_time": "true", "autostart": "true",
                          "params_file": _nav2_params(tb3_nav)}.items())]))

    if CONFIG["rviz"]:
        actions.append(Node(package="rviz2", executable="rviz2", name="rviz2", output="log",
                            arguments=["-d", os.path.join(tb3_nav, "rviz", "tb3_navigation2.rviz")],
                            parameters=[{"use_sim_time": True}]))
    return LaunchDescription(actions)
'''


def render(cfg: LaunchConfig) -> str:
    """Python source of the launch file for this config."""
    if not cfg.world_name:
        raise ValueError("world_name is required (the robot is spawned into it by name)")
    literal = pprint.pformat(asdict(cfg), indent=4, sort_dicts=True, width=100)
    return _TEMPLATE.replace("__CONFIG__", literal)


def write(cfg: LaunchConfig, out_dir: Path | None = None) -> Path:
    path = Path(out_dir or cfg.run_dir) / LAUNCH_FILE
    path.write_text(render(cfg), encoding="utf-8")
    return path
