def _ros(params, node):
    return params.setdefault(node, {}).setdefault("ros__parameters", {})


NAV_GOAL_TOLERANCE_M = 0.12        # where Nav2 aims (robust profile)
MISSION_GOAL_TOLERANCE_M = 0.25    # what counts as "reached" in the score (TurtleBot3's stock goal checker)
SCORING_FILE = "scoring.l2s.json"  # read by telemetry/benchmark.py:scoring_params

# Regulated Pure Pursuit: follows the (2 Hz re-planned) global path exactly, slows down near obstacles, rotates
# in place toward a sharp detour instead of arcing into the obstacle, and stops if the path ahead would collide.
RPP = {
    "plugin": "nav2_regulated_pure_pursuit_controller::RegulatedPurePursuitController",
    "desired_linear_vel": 0.26, "lookahead_dist": 0.6, "min_lookahead_dist": 0.3, "max_lookahead_dist": 0.9,
    "lookahead_time": 1.5, "rotate_to_heading_angular_vel": 1.0, "transform_tolerance": 0.5,
    "use_velocity_scaled_lookahead_dist": False, "min_approach_linear_velocity": 0.05,
    "approach_velocity_scaling_dist": 0.6, "use_collision_detection": True,
    "max_allowed_time_to_collision_up_to_carrot": 1.0, "use_regulated_linear_velocity_scaling": True,
    "use_cost_regulated_linear_velocity_scaling": True, "regulated_linear_scaling_min_radius": 0.9,
    "regulated_linear_scaling_min_speed": 0.1, "cost_scaling_dist": 0.4, "cost_scaling_gain": 1.0,
    "inflation_cost_scaling_factor": 3.0, "use_rotate_to_heading": True, "rotate_to_heading_min_angle": 0.6,
    "max_angular_accel": 3.2, "max_robot_pose_search_dist": 10.0, "allow_reversing": False,
    "use_fixed_curvature_lookahead": False, "interpolate_curvature_after_goal": False, "stateful": True,
}
# Smac 2D (A* on the costmap): cost_travel_multiplier keeps the path in the middle of a gap, away from racks
# and dropped obstacles, instead of NavFn's shortest line along their inflation edge.
SMAC_2D = {
    "plugin": "nav2_smac_planner::SmacPlanner2D", "tolerance": 0.25, "downsample_costmap": False,
    "downsampling_factor": 1, "allow_unknown": True, "max_iterations": 1000000, "max_on_approach_iterations": 1000,
    "max_planning_time": 2.0, "cost_travel_multiplier": 2.0, "use_final_approach_orientation": False,
    "smoother": {"max_iterations": 1000, "w_smooth": 0.3, "w_data": 0.2, "tolerance": 1.0e-10},
}


def _robust(params):
    """Obstacle-aware tuning (L2S_NAV_PROFILE=robust, the default; "stock" keeps the TurtleBot3 file).

    - planner: Smac 2D with a travel cost, so the path goes through the middle of the gap beside a
      dropped obstacle; inflation 0.55 m with a gentle 3.0 decay so that middle is clearly cheapest;
    - controller: Regulated Pure Pursuit instead of DWB. DWB scored trajectories on a short horizon and
      cut the detour's corner until the robot sat nose-to-crate with 20+ recoveries (measured, see
      docs/navigation.md); RPP tracks the re-planned path and turns in place for sharp detours;
    - the costmaps use the Waffle's real chassis rectangle instead of a 0.15 m circle that is smaller
      than the robot; the global costmap updates and the tree replans at 2 Hz;
    - turning in place counts as progress; recoveries back up before spinning, 10 retries instead of 6.
    MPPI stalled for minutes between racks on a 2-core machine, so it is not used.
    """
    for key, size in (("global_costmap", None), ("local_costmap", 4)):
        cm = params.get(key, {}).get(key, {}).get("ros__parameters")
        if cm is None:
            continue
        cm.pop("robot_radius", None)
        cm["footprint"] = WAFFLE_FOOTPRINT
        cm["footprint_padding"] = 0.02
        infl = cm.get("inflation_layer")
        if isinstance(infl, dict):
            infl["inflation_radius"] = 0.55
            infl["cost_scaling_factor"] = 3.0
        if size:
            cm["width"] = cm["height"] = size
        else:
            cm["update_frequency"] = 2.0
            cm["publish_frequency"] = 1.0
    ctl = _ros(params, "controller_server")
    ctl["progress_checker_plugins"] = ["progress_checker"]
    ctl["progress_checker"] = {"plugin": "nav2_controller::PoseProgressChecker", "required_movement_radius": 0.2,
                               "required_movement_angle": 0.5, "movement_time_allowance": 15.0}
    ctl["FollowPath"] = dict(RPP)
    # Aim well inside the mission's success radius: RPP stops as soon as AMCL says "within tolerance", and
    # AMCL's estimate was 0.15-0.19 m off ground truth at the goal, so a 0.25 m checker ended runs 0.28-0.34 m
    # from the goal and the score said "failed" although Nav2 said "succeeded". The score keeps 0.25 m.
    checker = ctl.setdefault("goal_checker", {"plugin": "nav2_controller::SimpleGoalChecker", "stateful": True})
    checker["xy_goal_tolerance"] = NAV_GOAL_TOLERANCE_M
    with open(os.path.join(CONFIG["run_dir"], SCORING_FILE), "w") as f:
        json.dump({"goal_tolerance_m": MISSION_GOAL_TOLERANCE_M, "goal_tolerance_source": "mission",
                   "nav2_goal_checker_m": NAV_GOAL_TOLERANCE_M}, f)
    # AMCL: Gazebo's wheel odometry is nearly exact, so trust it more (stock alphas 0.2 assume a noisy real robot)
    # and update the filter every 10 cm / 0.1 rad instead of 25 cm / 0.2 rad.
    amcl = _ros(params, "amcl")
    amcl.update({"alpha1": 0.05, "alpha2": 0.05, "alpha3": 0.05, "alpha4": 0.05, "alpha5": 0.05,
                 "update_min_d": 0.1, "update_min_a": 0.1, "max_beams": 120})
    planner = _ros(params, "planner_server")
    planner["planner_plugins"] = ["GridBased"]
    planner["GridBased"] = dict(SMAC_2D)
    planner["expected_planner_frequency"] = 2.0
    bt_path = os.path.join(CONFIG["run_dir"], "navigate_l2s.xml")
    with open(bt_path, "w") as f:
        f.write(ROBUST_BT)
    bt = _ros(params, "bt_navigator")
    bt["default_nav_to_pose_bt_xml"] = bt_path
    cmon = _ros(params, "collision_monitor")
    if isinstance(cmon.get("FootprintApproach"), dict):
        cmon["FootprintApproach"]["time_before_collision"] = 1.5   # stock 2.0 s stalls the robot 0.6 m out


def _nav2_params(tb3_nav):
    """Base Nav2 params with AMCL seeded at the spawn pose, written into the run folder."""
    base = CONFIG["nav2_params"] or os.path.join(tb3_nav, "param", CONFIG["robot"] + ".yaml")
    with open(base) as f:
        params = yaml.safe_load(f)
    amcl = params.setdefault("amcl", {}).setdefault("ros__parameters", {})
    amcl["set_initial_pose"] = True
    amcl["initial_pose"] = {"x": float(CONFIG["x"]), "y": float(CONFIG["y"]), "z": 0.0,
                            "yaw": float(CONFIG["yaw"])}
    for cm_key in ("global_costmap", "local_costmap"):
        cm_dict = params.get(cm_key, {}).get(cm_key, {}).get("ros__parameters", {})
        infl = cm_dict.get("inflation_layer", {})
        if infl:
            infl["inflation_radius"] = 0.35
            infl["cost_scaling_factor"] = 5.0
    profile = os.environ.get("L2S_NAV_PROFILE", CONFIG.get("nav_profile", "robust"))
    if profile == "robust" and not CONFIG["nav2_params"]:
        _robust(params)
    out = os.path.join(CONFIG["run_dir"], "nav2_params.l2s.yaml")
    with open(out, "w") as f:
        yaml.safe_dump(params, f, sort_keys=False)
    return out


def generate_launch_description():
    tb3_gz = get_package_share_directory("turtlebot3_gazebo")
    tb3_nav = get_package_share_directory("turtlebot3_navigation2")
    ros_gz_sim = get_package_share_directory("ros_gz_sim")
    nav2_bringup = get_package_share_directory("nav2_bringup")
    model = "turtlebot3_" + CONFIG["robot"]

    with open(os.path.join(tb3_gz, "urdf", model + ".urdf")) as f:
        robot_description = f.read()

    actions = [AppendEnvironmentVariable("GZ_SIM_RESOURCE_PATH", p)
               for p in [os.path.join(tb3_gz, "models"), *CONFIG["resource_paths"]]]

    actions.append(IncludeLaunchDescription(
        PythonLaunchDescriptionSource(os.path.join(ros_gz_sim, "launch", "gz_sim.launch.py")),
        launch_arguments={"gz_args": "-r -s -v2 " + CONFIG["world_sdf"], "on_exit_shutdown": "true"}.items()))
    if CONFIG["gui"]:
        actions.append(IncludeLaunchDescription(
            PythonLaunchDescriptionSource(os.path.join(ros_gz_sim, "launch", "gz_sim.launch.py")),
            launch_arguments={"gz_args": "-g -v2", "on_exit_shutdown": "false"}.items()))

    actions.append(Node(
        package="robot_state_publisher", executable="robot_state_publisher", name="robot_state_publisher",
        output="screen", parameters=[{"use_sim_time": True, "robot_description": robot_description}]))
    actions.append(Node(
        package="ros_gz_sim", executable="create", output="screen",
        arguments=["-world", CONFIG["world_name"], "-name", CONFIG["robot"],
                   "-file", CONFIG["robot_sdf"] or os.path.join(tb3_gz, "models", model, "model.sdf"),
                   "-x", str(CONFIG["x"]), "-y", str(CONFIG["y"]), "-z", "0.01", "-Y", str(CONFIG["yaw"])]))
    actions.append(Node(
        package="ros_gz_bridge", executable="parameter_bridge", name="ros_gz_bridge", output="screen",
        parameters=[{"config_file": CONFIG["bridge_config"] or os.path.join(tb3_gz, "params", model + "_bridge.yaml"),
                     "use_sim_time": True}]))
    if CONFIG["camera"]:
        actions.append(Node(package="ros_gz_image", executable="image_bridge", name="ros_gz_image_bridge",
                            arguments=["/camera/image_raw"], output="screen"))

    actions.append(TimerAction(period=float(CONFIG["nav2_delay_s"]), actions=[IncludeLaunchDescription(
        PythonLaunchDescriptionSource(os.path.join(nav2_bringup, "launch", "bringup_launch.py")),
        launch_arguments={"map": CONFIG["map_yaml"], "use_sim_time": "true", "autostart": "true",
                          "params_file": _nav2_params(tb3_nav)}.items())]))

    if CONFIG["rviz"]:
        actions.append(Node(package="rviz2", executable="rviz2", name="rviz2", output="log",
                            arguments=["-d", os.path.join(tb3_nav, "rviz", "tb3_navigation2.rviz")],
                            parameters=[{"use_sim_time": True}]))
    return LaunchDescription(actions)
