"""
Launch generator: one self-contained sim_launch.py per run.
File: lang2sim/runtime/launch_builder.py

Placed in runtime/ rather than compiler/ because the container imports it and
compiler/__init__.py pulls in jinja2/shapely, which the sim image does not ship.

The generated file is plain ROS 2 Python launch code with this run's settings
baked in as a dict literal at the top, so it can be read, diffed and re-run by
hand:  ros2 launch <run_dir>/sim_launch.py

It starts: Gazebo server (+ optional GUI that may be closed without stopping the
sim), robot_state_publisher, the TurtleBot3 Waffle spawned at the manifest's
pose, ros_gz_bridge (+ optional camera bridge), Nav2 with this run's map and AMCL
seeded at the spawn pose, and optional RViz2.

With telemetry on, the robot is spawned from the run's robot.l2s.sdf (chassis
bumper + ground-truth pose, see robot_instrument.py) and the bridge loads
bridge.l2s.yaml (stock topics + /lang2sim/contact_states and
/lang2sim/ground_truth/odom).
"""

from __future__ import annotations

import pprint
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import List

LAUNCH_FILE = "sim_launch.py"


@dataclass(frozen=True)
class LaunchConfig:
    run_dir: str                       # container path; logs and generated params go here
    world_sdf: str                     # container path, already checked/normalized
    world_name: str
    map_yaml: str
    x: float = 0.0
    y: float = 0.0
    yaw: float = 0.0
    gui: bool = True
    rviz: bool = True
    camera: bool = True                # image bridge; heavy under software rendering
    nav2_params: str = ""              # "" -> TurtleBot3 Waffle params
    nav2_delay_s: float = 5.0
    resource_paths: List[str] = field(default_factory=list)  # extra GZ_SIM_RESOURCE_PATH entries
    robot: str = "waffle"
    robot_sdf: str = ""                # "" -> stock TurtleBot3 model.sdf; else robot.l2s.sdf (bumper + ground truth)
    bridge_config: str = ""            # "" -> stock TurtleBot3 bridge yaml; else bridge.l2s.yaml (+ telemetry topics)
    nav_profile: str = "robust"        # "robust": obstacle-aware Nav2 tuning; "stock": TurtleBot3 defaults ($L2S_NAV_PROFILE wins)


